import { afterAll, beforeAll, describe, expect, test } from "bun:test";
import { mkdir, mkdtemp, readFile, realpath, rm, symlink, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { buildAddArgs, buildCommitArgs, validateMessage } from "../../../scripts/git/commit";
import { artifactPath, ARTIFACTS, assertUnder, writeIsolatedConfig } from "../../../scripts/lib/artifacts";

describe("commit.ts helpers", () => {
  test("validateMessage accepts valid conventional headers", () => {
    expect(validateMessage("chore(bootstrap): scaffold")).toBeNull();
    expect(validateMessage("feat: sem escopo\n\ncorpo")).toBeNull();
    expect(validateMessage("fix(core)!: breaking")).toBeNull();
  });

  test("validateMessage rejects Co-Authored-By trailer (any case)", () => {
    expect(validateMessage("feat(x): ok\n\nCo-Authored-By: Someone <a@b.c>")).not.toBeNull();
    expect(validateMessage("feat(x): ok\n\nco-authored-by: someone")).not.toBeNull();
  });

  test("validateMessage rejects 'Generated with'", () => {
    expect(validateMessage("feat(x): ok\n\nGenerated with a tool")).not.toBeNull();
  });

  test("validateMessage rejects bad headers", () => {
    expect(validateMessage("")).not.toBeNull();
    expect(validateMessage("update stuff")).not.toBeNull();
    expect(validateMessage("wip(x): nope")).not.toBeNull();
    expect(validateMessage("feat(x):nospace")).not.toBeNull();
  });

  test("validateMessage still accepts 'generate' as a plain verb", () => {
    expect(validateMessage("feat(core): generate year table")).toBeNull();
    expect(validateMessage("fix(x): ok\n\ncorpo com hífen-normal e — travessão")).toBeNull();
  });

  test.each([
    ["Co-authored by (space instead of hyphen)", "Co-authored by: Someone <a@b.c>"],
    ["Co-Authored-By with non-breaking hyphens", "Co\u2011Authored\u2011By: Someone <a@b.c>"],
    ["Co-Authored-By with zero-width space", "Co-\u200bAuthored-By: Someone <a@b.c>"],
    ["CoAuthoredBy without separators", "CoAuthoredBy: Someone"],
    ["Generated with double space", "Generated  with a tool"],
    ["Generated with NBSP", "Generated\u00a0with a tool"],
    ["Generated by (emoji prefix)", "\u{1F916} Generated by Claude"],
    ["Generated using", "Generated using some tool"],
    ["noreply@anthropic.com in Signed-off-by", "Signed-off-by: Claude <noreply@anthropic.com>"],
    ["Claude with an anthropic address", "Reviewed-by: Claude <bot@anthropic.com>"],
    ["fullwidth letters (NFKC)", "\uFF23o-authored-by: x"],
  ])("validateMessage rejects bypass: %s", (_label, body) => {
    expect(validateMessage(`feat(x): ok\n\n${body}`)).not.toBeNull();
  });

  test("buildAddArgs disables pathspec magic and lists only the given paths after --", () => {
    const args = buildAddArgs(["a.ts", "dir/b.ts"]);
    expect(args).toContain("--literal-pathspecs");
    expect(args.indexOf("--literal-pathspecs")).toBeLessThan(args.indexOf("add"));
    expect(args.slice(-3)).toEqual(["--", "a.ts", "dir/b.ts"]);
  });

  test("buildCommitArgs commits the message file and only the given paths", () => {
    const args = buildCommitArgs("msg.txt", [":(glob)*", "dir/b.ts"]);
    expect(args).toContain("commit");
    expect(args.slice(args.indexOf("-F"), args.indexOf("-F") + 2)).toEqual(["-F", "msg.txt"]);
    expect(args.slice(-4)).toEqual(["--only", "--", ":(glob)*", "dir/b.ts"]);
  });
});

describe("artifacts", () => {
  test("artifactPath joins under ARTIFACTS", () => {
    expect(artifactPath("state", "x.json")).toBe(join(ARTIFACTS, "state", "x.json"));
  });
});

describe("writeIsolatedConfig", () => {
  let base: string;

  beforeAll(async () => {
    base = await realpath(await mkdtemp(join(tmpdir(), "fc-isocfg-")));
  });

  afterAll(async () => {
    await rm(base, { recursive: true, force: true });
  });

  test("creates <dir>\\opencode\\opencode.json with exactly {}", async () => {
    const xdg = join(base, "fresh");
    const file = await writeIsolatedConfig(xdg);
    expect(file).toBe(join(xdg, "opencode", "opencode.json"));
    expect(await readFile(file, "utf8")).toBe("{}");
  });

  test("overwrites a leftover config (e.g. a probe plugin) with {}", async () => {
    const xdg = join(base, "stale");
    await mkdir(join(xdg, "opencode"), { recursive: true });
    const file = join(xdg, "opencode", "opencode.json");
    await writeFile(file, JSON.stringify({ plugin: ["D:\\future-probe\\probe.ts"] }));
    expect(await writeIsolatedConfig(xdg)).toBe(file);
    expect(await readFile(file, "utf8")).toBe("{}");
  });
});

describe("assertUnder", () => {
  let base: string;
  let root: string;
  let outside: string;

  beforeAll(async () => {
    base = await realpath(await mkdtemp(join(tmpdir(), "fc-assert-")));
    root = join(base, "root");
    outside = join(base, "outside");
    await mkdir(join(root, "nested"), { recursive: true });
    await mkdir(outside, { recursive: true });
    await symlink(outside, join(root, "link"), "junction");
  });

  afterAll(async () => {
    await rm(base, { recursive: true, force: true });
  });

  test("accepts a nested path (existing or not)", async () => {
    expect(await assertUnder(root, join(root, "nested"))).toBe(join(root, "nested"));
    expect(await assertUnder(root, join(root, "nested", "new", "file.txt"))).toBe(
      join(root, "nested", "new", "file.txt"),
    );
  });

  test("rejects '..' segments", async () => {
    await expect(assertUnder(root, `${root}\\nested\\..\\..\\outside`)).rejects.toThrow();
    await expect(assertUnder(root, `${root}/nested/../x`)).rejects.toThrow();
  });

  test("rejects dot-only segments that Windows may treat as '..'", async () => {
    await expect(assertUnder(root, `${root}\\nested\\.. \\x`)).rejects.toThrow();
    await expect(assertUnder(root, `${root}\\nested\\...\\x`)).rejects.toThrow();
    await expect(assertUnder(root, `${root}\\nested\\.. .\\x`)).rejects.toThrow();
    await expect(assertUnder(root, `${root}\\nested\\..`)).rejects.toThrow();
  });

  test("accepts names that merely contain dots", async () => {
    expect(await assertUnder(root, join(root, "nested", "..x", "a..b.txt"))).toBe(
      join(root, "nested", "..x", "a..b.txt"),
    );
  });

  test("accepts a mixed-case spelling of the root", async () => {
    const mixed = root.replace(/[a-z]/g, (c, i: number) => (i % 2 === 0 ? c.toUpperCase() : c));
    const target = join(root, "nested", "file.txt");
    if (process.platform === "win32") {
      expect(await assertUnder(mixed, target)).toBe(target);
    }
    await expect(assertUnder(mixed, outside)).rejects.toThrow();
  });

  test("rejects UNC and relative paths", async () => {
    await expect(assertUnder(root, "\\\\server\\share\\x")).rejects.toThrow();
    await expect(assertUnder(root, "//server/share/x")).rejects.toThrow();
    await expect(assertUnder(root, "nested\\file.txt")).rejects.toThrow();
  });

  test("rejects a path outside the root", async () => {
    await expect(assertUnder(root, outside)).rejects.toThrow();
  });

  test("rejects a junction pointing outside the root", async () => {
    await expect(assertUnder(root, join(root, "link"))).rejects.toThrow();
    await expect(assertUnder(root, join(root, "link", "file.txt"))).rejects.toThrow();
  });
});
